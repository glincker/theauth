// Writes migrations/0001_initial.sql from the same feature options the worker
// passes to createTheAuth. Re-run it (and add a new numbered file) after you
// turn on more features, then apply with `wrangler d1 migrations apply`.
import { mkdirSync, writeFileSync } from "node:fs";
import { getMigrationStatements } from "@glinr/theauth";

// Keep in sync with the options in src/worker.ts. Only the presence of a
// feature decides which tables are created, so the secret value is a stand in.
const statements = getMigrationStatements("d1", {
	auth: { session: { secret: "placeholder" } },
	agents: { enabled: true },
});

const header = "-- Generated by scripts/generate-migration.mjs. Do not edit by hand.\n\n";
const body = statements.map((sql) => `${sql};`).join("\n\n");

mkdirSync(new URL("../migrations/", import.meta.url), { recursive: true });
writeFileSync(new URL("../migrations/0001_initial.sql", import.meta.url), `${header}${body}\n`);
