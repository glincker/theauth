#!/usr/bin/env node
/**
 * Turn a results JSON file from run.mjs into markdown tables that can be pasted
 * into docs/benchmarks.mdx.
 *
 *   node benchmarks/report.mjs benchmarks/results/full.json --out benchmarks/results/full.md
 */
import { readFileSync, writeFileSync } from "node:fs";

const [, , input, ...rest] = process.argv;
if (!input) {
	console.error("Usage: node benchmarks/report.mjs <results.json> [--out report.md]");
	process.exit(2);
}
const outIdx = rest.indexOf("--out");
const outPath = outIdx >= 0 ? rest[outIdx + 1] : null;

const data = JSON.parse(readFileSync(input, "utf8"));
const hw = data.hardware;

const fmt = (n, digits = 3) => (n === null || n === undefined ? "n/a" : Number(n).toFixed(digits));
const fmtOps = (n) =>
	n === null || n === undefined ? "n/a" : Math.round(n).toLocaleString("en-US");

const lines = [];
const push = (s = "") => lines.push(s);

push(`<!-- Generated by benchmarks/report.mjs from ${input}. Do not edit by hand. -->`);
push();
push("## Hardware and environment");
push();
push("| Item | Value |");
push("| --- | --- |");
push(`| Node | ${hw.nodeVersion} |`);
push(`| CPU | ${hw.cpuModel} (${hw.cpuCount} logical cores) |`);
push(`| Memory | ${hw.memoryGb} GB |`);
push(`| Platform | ${hw.platform} |`);
push(`| Commit | ${hw.commit ?? "unknown"} |`);
push(`| CI runner | ${hw.ci ? "yes" : "no"} |`);
push(`| Profile | ${data.profile} |`);
push(`| Generated | ${data.generatedAt} |`);
push();
push("## How to reproduce");
push();
push("```bash");
push("pnpm install --frozen-lockfile");
push(data.profile === "full" ? "pnpm bench:ci" : "pnpm bench:smoke");
push("```");
push();
push("The exact invocation behind this file:");
push();
push("```bash");
push(data.command);
push("```");
push();
if (data.profile !== "full") {
	push(
		"> This is a smoke run with a handful of iterations. It proves the harness executes. Do not quote these numbers.",
	);
	push();
}

const s = data.profileSettings;
push("## Methodology");
push();
push(
	`Each row times one operation with \`performance.now()\` after ${s.warmup} warmup calls that are not recorded. Percentiles use the nearest-rank method over every recorded sample. Ops per second is completed operations divided by wall time for the whole measurement. RSS delta is resident set size after the measurement minus before it, in MB (garbage collection is forced before each reading only when Node runs with \`--expose-gc\`; the CI command does). Iteration counts: cheap in-process calls ${s.fast.toLocaleString("en-US")}, database calls ${s.db.toLocaleString("en-US")}, audit appends ${s.audit.toLocaleString("en-US")}, password hashes ${s.slow.toLocaleString("en-US")}.`,
);
push();
push(
	"Concurrency values are async tasks interleaved on one Node event loop, not threads. They show how a backend and the audit queue behave when many writers await at once. They do not show multi-core scaling.",
);
push();

const byBackend = new Map();
for (const r of data.results) {
	if (!byBackend.has(r.backend)) byBackend.set(r.backend, []);
	byBackend.get(r.backend).push(r);
}

for (const [backend, rows] of byBackend) {
	push(`## Backend: ${backend}`);
	push();
	const scenarios = [...new Set(rows.map((r) => r.scenario))];
	for (const scenario of scenarios) {
		push(`### ${scenario}`);
		push();
		push(
			"| Variant | Conc. | Iterations | p50 (ms) | p95 (ms) | p99 (ms) | ops/sec | RSS delta (MB) | Errors |",
		);
		push("| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |");
		for (const r of rows.filter((x) => x.scenario === scenario)) {
			const l = r.latencyMs;
			push(
				`| ${r.variant} | ${r.concurrency} | ${r.iterations.toLocaleString("en-US")} | ${fmt(l.p50)} | ${fmt(l.p95)} | ${fmt(l.p99)} | ${fmtOps(r.opsPerSec)} | ${fmt(r.rssDeltaAfterGcMb ?? r.rssDeltaMb, 1)} | ${r.errors} |`,
			);
		}
		push();
	}
}

if (data.skippedBackends.length > 0) {
	push("## Skipped backends");
	push();
	for (const k of data.skippedBackends) push(`- ${k.backend}: ${k.reason}`);
	push();
}
if (data.failures.length > 0) {
	push("## Failed scenarios");
	push();
	for (const f of data.failures) push(`- ${f.backend} / ${f.scenario}: ${f.message}`);
	push();
}

push("## Caveats");
push();
push(
	"- Numbers come from one machine and one run. Compare runs only when they used the same hardware, and treat gaps under roughly 10 percent as noise.",
);
push(
	"- GitHub-hosted runners share CPU with other jobs, so tail latencies (p99) are noisy there. Repeat the run before drawing conclusions from them.",
);
push(
	"- Postgres and MySQL run as service containers on the same host as the benchmark, so network latency is close to zero. A real deployment adds a round trip per query, which makes the number of queries per operation matter more than these timings suggest.",
);
push(
	"- The sql.js SQLite provider keeps the database in memory and, in file mode, writes the whole file after every mutation. Its file-mode rows measure that behavior, not SQLite itself.",
);
push(
	"- Audit contention rows use one process. Writers for the same agent queue inside that process, so they do not hit the unique index retry path. The multi-instance rows (Postgres and MySQL only) open several independent instances on one database to exercise that path.",
);
push(
	"- Scenarios share one database per backend, so table sizes grow as the run goes on. Operations that scan or count by owner or agent slow down with that growth; the createAgent rows are the clearest example.",
);
push();

const md = `${lines.join("\n")}\n`;
if (outPath) {
	writeFileSync(outPath, md);
	console.log(`wrote ${outPath}`);
} else {
	process.stdout.write(md);
}
